/**
 * The data the dust wallet's API speaks, in types the SDK owns.
 *
 * @remarks
 *   Everything here is plain data that both ledger versions report identically, so both variants are stated in these
 *   types and neither ledger version has to be named to read what a dust wallet emits. Each variant's tree re-exports
 *   them under the names it always had. Kept apart from `DustWalletAPI.ts`, which the package exports flat: these it
 *   exports under the wallet's name, as `DustWalletTypes`, because several of them — `UtxoWithMeta`, `Balance` — are
 *   also another wallet's.
 */
import {
  type ProtocolVersion,
  TransactionHistoryStorage,
  type UnshieldedUtxo,
} from '@midnightntwrk/wallet-sdk-abstractions';
import { Array as EArray, Schema } from 'effect';

/** A dust public key: the identity dust is generated for. */
export type DustPublicKey = bigint;

/** A dust UTxO's nonce. */
export type DustNonce = bigint;

/** The nonce of the Night UTxO that backs a dust UTxO, as hexadecimal. */
export type DustInitialNonce = string;

/** A dust UTxO. */
export type Dust = {
  initialValue: bigint;
  owner: DustPublicKey;
  nonce: DustNonce;
  seq: number;
  ctime: Date;
  backingNight: DustInitialNonce;
  mtIndex: bigint;
};

/** Details of Dust generation/decay */
export type DustGenerationDetails = {
  /** When the backing Night UTxO was spent */
  dtime: Date | undefined;
  /** Maximum capacity (in Specks) `gen.value * night_dust_ratio` */
  maxCap: bigint;
  /** When the maximum capacity is reached. `ctime + timeToCapSeconds` */
  maxCapReachedAt: Date;
  /** Current amount of Dust available (in Specks) */
  generatedNow: bigint;
  /** The slope of generation and decay for this specific Dust UTxO (`gen.value * generation_decay_rate`) */
  rate: bigint;
};

export type DustFullInfo = DustGenerationDetails & {
  token: Dust;
};

/**
 * The Night UTxO backing a dust UTxO, as dust generation sees it: its value, the dust public key it generates for, its
 * nonce, and when it was spent, if it has been.
 */
export type DustGenerationInfo = {
  value: bigint;
  owner: DustPublicKey;
  nonce: DustInitialNonce;
  dtime: Date | undefined;
};

/** A Night UTxO, with what dust generation needs to know about it. */
export type UtxoWithMeta = UnshieldedUtxo & { ctime: Date; registeredForDustGeneration: boolean };

/** An amount of dust, in Specks. */
export type Balance = bigint;

/** A coin together with the amount of dust it holds. */
export type CoinWithValue<TToken> = {
  token: TToken;
  value: Balance;
};

/**
 * Type describing a Night UTxO together with details of estimated Dust generation. It is meant to be primarily used for
 * fee estimation of Dust registration transaction
 */
export type UtxoWithFullDustDetails = Readonly<{
  utxo: UtxoWithMeta;
  dust: DustGenerationDetails;
}>;

/**
 * Result of splitting Night UTxOs into the guaranteed/fallible sections of a Dust registration or deregistration
 * intent, together with the fee-payment allowance the registration may claim from dust generated by the guaranteed
 * UTxO.
 *
 * For deregistration, `feePayment` is always `0n`.
 */
export type NightUtxoSplitForDustRegistration = {
  readonly guaranteedUtxos: ReadonlyArray<UtxoWithFullDustDetails>;
  readonly fallibleUtxos: ReadonlyArray<UtxoWithFullDustDetails>;
  readonly feePayment: bigint;
};

/**
 * When the claimable fee payment of a set of Night UTxOs will reach a fee, or why it never will.
 *
 * @remarks
 *   `Reachable` gives the first whole second, counted from the time the estimate was made, at which the dust generated by
 *   some unregistered UTxO covers the fee; `seconds` is `0n` when one already does. `Unreachable` says no such second
 *   exists: `NoGeneration` when no unregistered UTxO generates any dust, `ExceedsCap` when some do but the fee is above
 *   the most any of them can ever hold.
 * @example
 *   ```ts
 *   const deadline = estimate._tag === 'Reachable' ? estimate.at : undefined; // undefined: waiting will not help
 *   ```;
 */
export type FeeCoverageEstimate =
  | { readonly _tag: 'Reachable'; readonly seconds: bigint; readonly at: Date }
  | { readonly _tag: 'Unreachable'; readonly reason: 'NoGeneration' | 'ExceedsCap' };

export type TotalCostParameters = {
  additionalFeeOverhead?: bigint;
  // a number of blocks we expect for finalization.
  feeBlocksMargin: number;
};

/** Where a chain's dust event timeline reaches a protocol boundary. */
export type DustTimelineStart = Readonly<{
  /** The last dust event id below the boundary: the cursor a variant registered from the boundary resumes after. */
  cursor: bigint;
  /** The version the first dust event at or beyond the boundary was reported at. */
  version: ProtocolVersion.ProtocolVersion;
}>;

export const DustUtxoInfoSchema = Schema.Struct({
  initialValue: Schema.BigInt,
  nonce: Schema.BigInt,
  seq: Schema.Number,
  backingNight: Schema.String,
  mtIndex: Schema.BigInt,
});

export const DustSectionSchema = Schema.Struct({
  receivedUtxos: Schema.Array(DustUtxoInfoSchema),
  spentUtxos: Schema.Array(DustUtxoInfoSchema),
});

type DustSection = Schema.Schema.Type<typeof DustSectionSchema>;

const utxoEquals = Schema.equivalence(DustUtxoInfoSchema);

/**
 * Merges two records of one transaction's dust section, so that a dust UTxO either of them records appears once.
 *
 * @param existing The section already stored.
 * @param incoming The section being written.
 * @returns The dust UTxOs received and spent according to either.
 */
export const mergeDustSections = (existing: DustSection, incoming: DustSection): DustSection => ({
  receivedUtxos: EArray.unionWith(existing.receivedUtxos, incoming.receivedUtxos, utxoEquals),
  spentUtxos: EArray.unionWith(existing.spentUtxos, incoming.spentUtxos, utxoEquals),
});

/**
 * Dust entry schema. Extends the common entry shape with an optional `dust` section. Tightening — required `dust` plus
 * required `protocolVersion`/`status`/`fees` — happens at the writer-input type, not on the stored shape.
 */
export const DustTransactionHistoryEntrySchema = TransactionHistoryStorage.extendEntrySchema({
  dust: Schema.optional(DustSectionSchema),
});

export type DustTransactionHistoryEntry = Schema.Schema.Type<typeof DustTransactionHistoryEntrySchema>;

export type DustHistoryStorage =
  TransactionHistoryStorage.TransactionHistoryReader<TransactionHistoryStorage.TransactionHistoryEntryWithHash> &
    TransactionHistoryStorage.TransactionHistoryWriter<DustTransactionHistoryEntry>;
