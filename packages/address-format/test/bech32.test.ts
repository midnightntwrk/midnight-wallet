import { EncryptionSecretKey } from '@midnightntwrk/ledger-v9';
import { bech32m } from '@scure/base';
import { describe, expect, it } from 'vitest';
import {
  BLSScalar,
  DustAddress,
  mainnet,
  MidnightBech32m,
  ScaleBigInt,
  ShieldedAddress,
  ShieldedCoinPublicKey,
  ShieldedEncryptionPublicKey,
  ShieldedEncryptionSecretKey,
  UnshieldedAddress,
} from '../src/index.js';
// The specification's own vectors, generated by its reference implementation. Read from where they are generated rather
// than copied, so a change to the specification fails here instead of leaving a stale copy passing.
import vectors from '../../spec-reference/test-vectors/addresses.json' with { type: 'json' };

type Vector = (typeof vectors)[number];
type Entry = { readonly hex: string; readonly bech32m: string };

// The vectors carry `networkId: null` for mainnet; the codecs use the `mainnet` symbol.
const networkOf = (vector: Vector) => vector.networkId ?? mainnet;
const describeVector = (vector: Vector) => `seed ${vector.seed} on ${vector.networkId ?? 'mainnet'}`;
const bytes = (hex: string) => Buffer.from(hex, 'hex');

// Some seeds derive no key of a given scheme; those vectors carry a null hex/bech32m pair.
const present = (pick: (vector: Vector) => { hex: string | null; bech32m: string | null }) =>
  vectors.flatMap((vector) => {
    const { hex, bech32m } = pick(vector);
    return hex !== null && bech32m !== null ? [{ vector, entry: { hex, bech32m } satisfies Entry }] : [];
  });

const unshieldedEntries = present((vector) => vector.unshieldedAddress);
const ecdsaEntries = present((vector) => vector.ecdsaAddress);

const testnetVector = vectors.find((vector) => vector.networkId === 'testnet');
const mainnetVector = vectors.find((vector) => vector.networkId === null);
if (testnetVector === undefined || mainnetVector === undefined) {
  throw new Error('the specification vectors no longer cover testnet and mainnet');
}

const withPayload = (type: string, network: string, payload: Buffer) => new MidnightBech32m(type, network, payload);

describe('the specification test vectors', () => {
  // The scheme-specific tests below skip vectors without a key of that scheme; this keeps them from passing on none.
  it('should include addresses of both unshielded signature schemes', () => {
    expect(unshieldedEntries.length).toBeGreaterThan(0);
    expect(ecdsaEntries.length).toBeGreaterThan(0);
  });

  describe('ShieldedAddress', () => {
    it('should decode each Bech32m string to the coin public key followed by the encryption public key', () => {
      vectors.forEach((vector) => {
        const address = ShieldedAddress.codec.decode(
          networkOf(vector),
          MidnightBech32m.parse(vector.shieldedAddress.bech32m),
        );

        expect(`${address.coinPublicKeyString()}${address.encryptionPublicKeyString()}`, describeVector(vector)).toBe(
          vector.shieldedAddress.hex,
        );
      });
    });

    it('should encode each pair of keys to exactly the specified Bech32m string', () => {
      // The address is the coin public key followed by the encryption public key, two hex digits per byte.
      const coinKeyHexLength = ShieldedCoinPublicKey.keyLength * 2;
      vectors.forEach((vector) => {
        const address = new ShieldedAddress(
          ShieldedCoinPublicKey.fromHexString(vector.shieldedAddress.hex.slice(0, coinKeyHexLength)),
          ShieldedEncryptionPublicKey.fromHexString(vector.shieldedAddress.hex.slice(coinKeyHexLength)),
        );

        expect(ShieldedAddress.codec.encode(networkOf(vector), address).asString(), describeVector(vector)).toBe(
          vector.shieldedAddress.bech32m,
        );
      });
    });
  });

  describe('ShieldedCoinPublicKey', () => {
    it('should decode each Bech32m string to the specified key', () => {
      vectors.forEach((vector) => {
        const key = ShieldedCoinPublicKey.codec.decode(
          networkOf(vector),
          MidnightBech32m.parse(vector.shieldedCPK.bech32m),
        );

        expect(key.toHexString(), describeVector(vector)).toBe(vector.shieldedCPK.hex);
      });
    });

    it('should encode each key to exactly the specified Bech32m string', () => {
      vectors.forEach((vector) => {
        const key = ShieldedCoinPublicKey.fromHexString(vector.shieldedCPK.hex);

        expect(ShieldedCoinPublicKey.codec.encode(networkOf(vector), key).asString(), describeVector(vector)).toBe(
          vector.shieldedCPK.bech32m,
        );
      });
    });
  });

  describe('ShieldedEncryptionSecretKey', () => {
    it('should decode each Bech32m string to the ledger serialization of the specified key', () => {
      vectors.forEach((vector) => {
        const key = ShieldedEncryptionSecretKey.codec.decode(
          networkOf(vector),
          MidnightBech32m.parse(vector.shieldedESK.bech32m),
        );

        expect(
          Buffer.from(key.zswap.yesIKnowTheSecurityImplicationsOfThis_serialize()).toString('hex'),
          describeVector(vector),
        ).toBe(vector.shieldedESK.hex);
      });
    });

    it('should encode each key to exactly the specified Bech32m string', () => {
      vectors.forEach((vector) => {
        const key = new ShieldedEncryptionSecretKey(EncryptionSecretKey.deserialize(bytes(vector.shieldedESK.hex)));

        expect(
          ShieldedEncryptionSecretKey.codec.encode(networkOf(vector), key).asString(),
          describeVector(vector),
        ).toBe(vector.shieldedESK.bech32m);
      });
    });
  });

  // A Schnorr and an ECDSA unshielded address share the `addr` credential type: both are a 32-byte hash, so one codec
  // must serve both schemes.
  describe.each([
    { scheme: 'Schnorr', entries: unshieldedEntries },
    { scheme: 'ECDSA', entries: ecdsaEntries },
  ])('UnshieldedAddress ($scheme)', ({ entries }) => {
    it('should decode each Bech32m string to the specified address', () => {
      entries.forEach(({ vector, entry }) => {
        const address = UnshieldedAddress.codec.decode(networkOf(vector), MidnightBech32m.parse(entry.bech32m));

        expect(address.hexString, describeVector(vector)).toBe(entry.hex);
      });
    });

    it('should encode each address to exactly the specified Bech32m string', () => {
      entries.forEach(({ vector, entry }) => {
        const address = new UnshieldedAddress(bytes(entry.hex));

        expect(UnshieldedAddress.codec.encode(networkOf(vector), address).asString(), describeVector(vector)).toBe(
          entry.bech32m,
        );
      });
    });
  });

  describe('DustAddress', () => {
    it('should decode each Bech32m string to the specified SCALE-encoded public key', () => {
      vectors.forEach((vector) => {
        const address = DustAddress.codec.decode(networkOf(vector), MidnightBech32m.parse(vector.dustAddress.bech32m));

        expect(address.hexString, describeVector(vector)).toBe(vector.dustAddress.hex);
      });
    });

    it('should encode each public key to exactly the specified Bech32m string', () => {
      vectors.forEach((vector) => {
        const address = new DustAddress(ScaleBigInt.decode(bytes(vector.dustAddress.hex)));

        expect(DustAddress.codec.encode(networkOf(vector), address).asString(), describeVector(vector)).toBe(
          vector.dustAddress.bech32m,
        );
      });
    });
  });
});

describe('the mainnet network id', () => {
  it('should treat the string "mainnet" as the mainnet symbol, so a mainnet address carries no network segment', () => {
    const address = new DustAddress(ScaleBigInt.decode(bytes(mainnetVector.dustAddress.hex)));

    expect(DustAddress.codec.encode('mainnet', address).asString()).toBe(mainnetVector.dustAddress.bech32m);
    expect(
      DustAddress.codec.decode('mainnet', MidnightBech32m.parse(mainnetVector.dustAddress.bech32m)).hexString,
    ).toBe(mainnetVector.dustAddress.hex);
  });
});

describe('decoding rejects', () => {
  describe('an address for a different network', () => {
    const testnetDust = MidnightBech32m.parse(testnetVector.dustAddress.bech32m);
    const mainnetDust = MidnightBech32m.parse(mainnetVector.dustAddress.bech32m);

    it('should reject a testnet address when decoding for devnet', () => {
      expect(() => DustAddress.codec.decode('devnet', testnetDust)).toThrow('Expected devnet address, got testnet one');
    });

    it('should reject a testnet address when decoding for mainnet', () => {
      expect(() => DustAddress.codec.decode(mainnet, testnetDust)).toThrow('Expected mainnet address, got testnet one');
    });

    it('should reject a mainnet address when decoding for testnet', () => {
      expect(() => DustAddress.codec.decode('testnet', mainnetDust)).toThrow(
        'Expected testnet address, got mainnet one',
      );
    });
  });

  // An unshielded address and a coin public key are both 32 bytes, so either payload would decode as the other: only
  // the credential type keeps one from being read as the other.
  describe('a credential of a different type with a payload of the same size', () => {
    const unshielded = unshieldedEntries.find(({ vector }) => vector.networkId === 'testnet');
    if (unshielded === undefined) {
      throw new Error('the specification vectors no longer cover a testnet unshielded address');
    }

    it('should reject a coin public key when decoding an unshielded address', () => {
      expect(() =>
        UnshieldedAddress.codec.decode('testnet', MidnightBech32m.parse(testnetVector.shieldedCPK.bech32m)),
      ).toThrow('Expected type addr, got shield-cpk');
    });

    it('should reject an unshielded address when decoding a coin public key', () => {
      expect(() =>
        ShieldedCoinPublicKey.codec.decode('testnet', MidnightBech32m.parse(unshielded.entry.bech32m)),
      ).toThrow('Expected type shield-cpk, got addr');
    });
  });

  describe('a malformed human-readable part', () => {
    // Checksummed correctly, so the Bech32m layer accepts it and only Midnight's own rules can reject it.
    const encodeRaw = (prefix: string) => bech32m.encode(prefix, bech32m.toWords(Buffer.alloc(32)), false);

    it('should reject a prefix other than "mn"', () => {
      expect(() => MidnightBech32m.parse(encodeRaw('xx_dust_testnet'))).toThrow('Expected prefix mn');
    });

    it.each([
      { case: 'a disallowed character in the type', prefix: 'mn_du$t_testnet', segment: 'type' },
      { case: 'an empty type', prefix: 'mn__testnet', segment: 'type' },
      { case: 'an empty network', prefix: 'mn_dust_', segment: 'network' },
      { case: 'a disallowed character in the network', prefix: 'mn_dust_test.net', segment: 'network' },
    ])('should reject $case', ({ prefix, segment }) => {
      expect(() => MidnightBech32m.parse(encodeRaw(prefix))).toThrow(`Segment ${segment}:`);
    });

    it.each([
      { case: 'a disallowed character in the type', type: 'du$t', network: 'testnet', segment: 'type' },
      { case: 'an underscore in the network', type: 'dust', network: 'test_net', segment: 'network' },
    ])('should refuse to construct a value with $case', ({ type, network, segment }) => {
      expect(() => new MidnightBech32m(type, network, Buffer.alloc(32))).toThrow(`Segment ${segment}:`);
    });
  });

  describe('a payload of the wrong size', () => {
    it.each([31, 33])('should reject a %i-byte coin public key', (size) => {
      expect(() =>
        ShieldedCoinPublicKey.codec.decode('testnet', withPayload('shield-cpk', 'testnet', Buffer.alloc(size))),
      ).toThrow('Coin public key needs to be 32 bytes long');
    });

    it.each([31, 33])('should reject a %i-byte unshielded address', (size) => {
      expect(() =>
        UnshieldedAddress.codec.decode('testnet', withPayload('addr', 'testnet', Buffer.alloc(size))),
      ).toThrow('Unshielded address needs to be 32 bytes long');
    });
  });

  describe('a Dust public key outside the scalar field', () => {
    it('should accept the largest field element', () => {
      const largest = BLSScalar.modulus - 1n;
      const decoded = DustAddress.codec.decode(
        'testnet',
        DustAddress.codec.encode('testnet', new DustAddress(largest)),
      );

      expect(decoded.data).toBe(largest);
    });

    it('should reject an encoded key at the field modulus', () => {
      const payload = ScaleBigInt.encode(BLSScalar.modulus);

      expect(() => DustAddress.codec.decode('testnet', withPayload('dust', 'testnet', payload))).toThrow(
        'Dust address is too large',
      );
    });

    it('should reject a valid key followed by trailing bytes', () => {
      const valid = bytes(testnetVector.dustAddress.hex);

      expect(DustAddress.codec.decode('testnet', withPayload('dust', 'testnet', valid)).hexString).toBe(
        testnetVector.dustAddress.hex,
      );
      expect(() =>
        DustAddress.codec.decode('testnet', withPayload('dust', 'testnet', Buffer.concat([valid, Buffer.from([0])]))),
      ).toThrow('Unprocessed data left');
    });
  });
});
